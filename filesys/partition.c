int part_initPartition(Partition *part, uint8_t refDisc)
{
	int c;

	part->disc = refDisc;

	// load MBR
	disc_ReadSector( part->disc, 0x00, sbuffer );

    if( ( sbuffer[ 510 ] != 0x55 ) || ( sbuffer[ 511 ] != 0xAA ) )
    {
        // unable to read MBR
        return -1;
    }

	// read partition table
    for(c=0; c<TOTAL_PARTITIONS; c++)
    {
    	ex_getPartitionField(sbuffer, &(part->partitions[c]),PARTITION_TABLE_OFFSET+(c*SIZE_PARTITION_FIELD));
		part->partitions[c].lun = refDisc;
    }

	return 0;
}

char part_getVolumeName( PartitionField * part, uint32_t loc, char * name )
{
	int i;
    uint8_t * buf;

	buf = part_getSect( part, loc, 0 );
	strcpy( name, "/" );

	for( i = 0; i < 11; i++ )
	{
		if( buf[i] <= 0x20 ) break;
		if( ( buf[i] >= 'A' ) && ( buf[i] <= 'Z' ) )  name[i+1] = buf[i] | 0x20;
		else name[i+1] = buf[i];
		name[i+2] = 0;
	}

	return 0;
}

