int part_writeBuf(PartitionField *part,uint32_t address,uint8_t* buf)
{
	return(disc_WriteSector(part->lun, (uint64_t)((part->LBA_begin+address)*512),buf));
}

uint8_t* part_getSect(PartitionField *part, uint32_t address, uint8_t * buf)
{
	disc_ReadSector(part->lun, (uint64_t)((part->LBA_begin+address)*512), sbuffer);
	if( buf != NULL ) memcpy( buf, sbuffer, 512 );
	return( sbuffer );
}

int part_CreateDefaultMBR( Partition * part )
{
	memset( sbuffer, 0x00, sizeof( sbuffer ) );
	if( disc_WriteSector(part->disc, 0, sbuffer) == MAL_FAIL ) return 1;

	memset( part->partitions, 0x00, sizeof( part->partitions ) );

	part->partitions[0].bootFlag = 0;
	part->partitions[0].LBA_begin = 0x80;
	part->partitions[0].numSectors = disc_GetSectorCount( part->disc ) - 0x80;
	part->partitions[0].type = PT_FAT16;

	if( part->partitions[0].numSectors < 32768 ) part->partitions[0].type = PT_FAT12;
	else if( part->partitions[0].numSectors < 262144 ) part->partitions[0].type = PT_FAT16;

	memset( part->partitions[0].CHS_begin, 0x00, sizeof( part->partitions[0].CHS_begin ) );
	memset( part->partitions[0].CHS_end, 0x00, sizeof( part->partitions[0].CHS_end ) );

	return part_UpdatePartitionTable( part );
}

int part_UpdatePartitionTable( Partition * part )
{
	uint8_t c;

	disc_ReadSector(part->disc, 0, sbuffer);

	// read partition table
    for(c=0; c<TOTAL_PARTITIONS; c++)
    {
    	ex_setPartitionField(sbuffer, &(part->partitions[c]),PARTITION_TABLE_OFFSET+(c*SIZE_PARTITION_FIELD));
    }

	sbuffer[510] = 0x55;
	sbuffer[511] = 0xAA;

	if( disc_WriteSector(part->disc, 0, sbuffer) == MAL_OK ) return 0;
	return 1;
}

int part_FormatPartition( PartitionField *part, uint8_t part_index, char * volume )
{
	uint32_t size;
	int i;
	char * p_volume = &volume[1];
    char * fat_sector;
    
    uint32_t fat1_secnum;
    uint32_t fat2_secnum;
    uint32_t root_secnum;
    
	// get partition size
	size = part->numSectors;
	
    // write boot sector
	memcpy( sbuffer, boot_sector, 512 );
	sbuffer[19] = (size & 0x0FF);
	sbuffer[20] = (size >> 8) & 0xFF;
    
    if( part->type ==  PT_FAT12 )
    {
        // 2 sectors per cluster
        sbuffer[13] = 0x02;
        
        // 224 root sectors
        sbuffer[17] = 0xe0;
        sbuffer[18] = 0x00;
        
        // fat sector
        fat_sector = ( char * )&fat12_sector[0];
        
        fat1_secnum = 1;
        fat2_secnum = 10;
        root_secnum = 19;
    }
    else if( part->type ==  PT_FAT16 )
    {
        // 8 sectors per cluster
        sbuffer[13] = 0x08;

        // 512 root sectors
        sbuffer[17] = 0x00;
        sbuffer[18] = 0x02;

        // fat sector
        fat_sector = ( char * )&fat16_sector[0];

        fat1_secnum = 0x0004;
        fat2_secnum = 0x000e;
        root_secnum = 0x0018;
    }
    else
    {
        return -1;
    }
    
    part_writeBuf( part, 0x0000, sbuffer );

    // write FAT
	memset( sbuffer, 0x00, 512 );
	memcpy( sbuffer, fat16_sector, 16 );
	part_writeBuf( part, fat1_secnum, sbuffer );
    
    // write FAT backup
	part_writeBuf( part, fat2_secnum, sbuffer );

    // write root volume
	memset( sbuffer, 0x00, 512 );
	memcpy( sbuffer, root_volume, 64 );

	for( i = 0; i < (int)strlen( p_volume ); i++ )
	{
		if( p_volume[i] <= 0x20 ) sbuffer[i] = '_';
		else if( ( p_volume[i] >= 'a' ) && ( p_volume[i] <= 'z' ) ) sbuffer[i] = p_volume[i] & ~0x20;
		else sbuffer[i] = p_volume[i];

		if( i >= 10 ) break;
	}

	part_writeBuf( part, root_secnum, sbuffer );
	return 0;
}
